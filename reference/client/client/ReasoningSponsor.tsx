/** Typed Host actions admitted for the legacy in-Think rewarded playback. */
export type SponsorPlaybackAction = 'start' | 'complete'

/** Typed Host actions admitted for the Tencent-compatible sandbox lifecycle. */
export type SponsorAdAction = 'load' | 'render' | 'impression'

/** Settled browser-facing result for one sandbox lifecycle transition. */
export interface SponsorAdActionResult {
  /** Present only when the transport or Host state machine refused the transition. */
  readonly error: string | null
  /** Host-issued request identity returned by `load`; never generated by the browser. */
  readonly opaqueId?: string
}

/** Addressed Remote face injected into the reasoning sponsor occupant. */
export interface ReasoningSponsorInjected {
  /** Record explicit one-time consent before any ad lifecycle transition. */
  readonly acceptSponsorship: (runId: string) => Promise<string | null>
  /** Admit one legacy playback transition for the exact durable run. */
  readonly updatePlayback: (
    runId: string,
    action: SponsorPlaybackAction,
  ) => Promise<string | null>
  /** Admit one Tencent sandbox transition; only `load` may omit `requestId`. */
  readonly updateAd: (
    runId: string,
    action: SponsorAdAction,
    requestId?: string,
  ) => Promise<SponsorAdActionResult>
  /** Revoke the unused provisional allowance after a local ad failure. */
  readonly failAd: (runId: string, reason: SponsorDemoAdFailureReason) => Promise<string | null>
}

/** Props for the single session-scoped reasoning sponsorship occupant. */
export type ReasoningSponsorProps = PropsRuntime<'conversation.chat.reasoning.sponsor'>
  & PropsLocale<'sponsorDemo'>
  & ReasoningSponsorInjected

type LocalError = 'accept' | 'asset' | 'load' | 'render' | 'impression' | 'playback' | 'start' | 'complete'
type PendingAction = 'accept' | SponsorPlaybackAction | SponsorAdAction
type LocalAdKind = 'video' | 'tencent-native-template' | 'unknown'

const COUNT_FORMAT = new Intl.NumberFormat('zh-CN')
const CURRENCY_FORMAT = new Intl.NumberFormat('zh-CN', {
  style: 'currency', currency: 'CNY', minimumFractionDigits: 2, maximumFractionDigits: 4,
})

function formatCount(value: number): string { return COUNT_FORMAT.format(value) }
function formatSeconds(valueMs: number): string { return String(Math.max(0, Math.round(valueMs / 1_000))) }
function formatMicros(value: number): string { return CURRENCY_FORMAT.format(value / 1_000_000) }

function clock(valueMs: number): string {
  const seconds = Math.max(0, Math.ceil(valueMs / 1_000))
  return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`
}

function resolveLocalAdKind(data: SponsoredRunChatData): LocalAdKind {
  if (
    data.assetId === LOCAL_SPONSOR_VIDEO_ASSET_ID
    && data.adProvider === 'local-video'
    && data.adFormat === 'rewarded-video'
  ) return 'video'
  const loadedMatches = data.adLoaded === undefined || (
    data.adLoaded.placementId === TENCENT_GDT_NATIVE_MOCK_PLACEMENT_ID
    && data.adLoaded.creativeId === TENCENT_GDT_NATIVE_MOCK_ASSET_ID
  )
  if (
    data.assetId === TENCENT_GDT_NATIVE_MOCK_ASSET_ID
    && data.adProvider === 'tencent-gdt-sandbox'
    && data.adFormat === 'native-template'
    && loadedMatches
  ) return 'tencent-native-template'
  return 'unknown'
}

function GrantLifecycle({ data, t }: {
  readonly data: SponsoredRunChatData
  readonly t: ReasoningSponsorProps['t']
}) {
  if (data.tokenGrant === undefined && data.tokenGrantSettlement === undefined) return null
  const verified = data.adVerification?.signatureVerified === true
    || data.tokenGrantSettlement !== undefined
  const settled = data.tokenGrantSettlement !== undefined
  const stages = [
    { label: t('reasoning.lifecycle.issued'), done: true },
    { label: t('reasoning.lifecycle.verified'), done: verified },
    { label: t('reasoning.lifecycle.settled'), done: settled },
  ]
  return (
    <ol className={css.grantLifecycle} aria-label={t('reasoning.lifecycle.aria')}>
      {stages.map((stage, index) => (
        <li key={stage.label} data-complete={stage.done ? 'true' : 'false'}>
          <span aria-hidden="true">{stage.done ? '✓' : index + 1}</span>
          {stage.label}
        </li>
      ))}
    </ol>
  )
}

